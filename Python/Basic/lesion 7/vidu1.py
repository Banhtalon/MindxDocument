n = int(input("Nhập vào số nguyên dương n: "))

# Khởi tạo biến tổng sum bằng 0
tong = 0
# Khởi tạo biến đếm i bằng 0
i = 0

# Sử dụng vòng lặp while để cộng dồn đến khi tổng lớn hơn n
while tong <= n:
    # Tăng biến đếm i lên 1 đơn vị
    i = i + 1
    # Cộng giá trị của i vào tổng
    tong = tong + i
    print (i)






















